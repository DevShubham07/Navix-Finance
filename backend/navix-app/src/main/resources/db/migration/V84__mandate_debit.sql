-- V84 — MandateDebit: one NACH debit PRESENTATION against a registered eMandate (V82) via Digio.
--
-- A presentation pulls real money from a real borrower's bank account. Digio offers no idempotency key,
-- so the only thing standing between a repayment and a double charge is OUR bookkeeping. Row per
-- ATTEMPT: a failed debit is followed by a new row (attempt_no counts up per loan), never an overwrite.
-- unique_key is our reconciliation handle — the key we recover an unknown-outcome presentation by
-- before ever presenting again.
--
-- THE DOUBLE-DEBIT GUARD is uq_mandate_debit_in_flight: at most ONE row per loan may be SCHEDULED or
-- IN_PROGRESS. A sweep racing a collections user's manual "debit", or two ECS tasks sweeping at once
-- (no ShedLock here), cannot be stopped by check-then-insert in application code; the database refuses
-- the second in-flight row outright. The service's advisory lock is the second layer, this is the first.
-- Terminal rows (SUCCEEDED/FAILED/FAILED_TECHNICAL/CANCELLED/SKIPPED) fall outside the index, so a
-- retry after a failure is allowed.
--
-- Money is BIGINT paise. The full account number is never stored (see mandate.account_last4).
-- No FK constraints, indexes only — the repo's documented, deliberate debt.
create table mandate_debit (
    id              bigint generated by default as identity primary key,
    mandate_id      bigint       not null,
    loan_id         bigint       not null,
    payment_id      bigint,
    digio_plan_id   varchar(64),
    digio_txn_id    varchar(64),
    unique_key      varchar(64)  not null,
    amount_paise    bigint       not null,
    settlement_date date,
    status          varchar(24)  not null,   -- SCHEDULED | IN_PROGRESS | SUCCEEDED | FAILED | FAILED_TECHNICAL | CANCELLED | SKIPPED
    digio_status    varchar(40),
    failure_code    varchar(64),
    failure_reason  varchar(500),
    utr             varchar(64),
    attempt_no      integer      not null,
    dpd_at_attempt  integer,
    triggered_by    varchar(16)  not null,   -- SCHEDULED | MANUAL
    actor_id        bigint,
    overpayment     boolean      not null default false,
    created_at      timestamptz  not null default now(),
    created_by      varchar(200),
    updated_at      timestamptz,
    updated_by      varchar(200),
    constraint uq_mandate_debit_unique_key unique (unique_key)
);
create unique index uq_mandate_debit_in_flight on mandate_debit (loan_id) where status in ('SCHEDULED', 'IN_PROGRESS');
create index ix_mandate_debit_loan on mandate_debit (loan_id);
create index ix_mandate_debit_mandate on mandate_debit (mandate_id);
create index ix_mandate_debit_status on mandate_debit (status);
