-- V93 — PayU Hosted Checkout for loan repayments.
--
-- payu_order is one row per checkout attempt (our txnid, the exact amount we asked PayU for, and what
-- PayU later confirmed). It is the idempotency anchor: a loan is credited once per order, keyed by
-- payment_id here and by the PayU mihpayid in payment.txn_ref (RepaymentService dedupes on txn_ref).
-- Amounts are BIGINT paise. Nothing in this table is a credential; PayU's key/salt live in SSM.
--
-- A PayU-confirmed payment is recorded VERIFIED in one step (no Accountant), so payment.method gains 'PAYU'.
-- V2 declared that CHECK inline, so the constraint name is whatever Postgres generated: drop every CHECK on
-- payment that mentions method rather than guess the name, then re-add it with the wider list.
--
-- Ships behind feature flag payu-repayment, OFF (read with defaultWhenMissing=FALSE, like digio-debit).
-- `do nothing` on conflict so a redeploy never overrides an operator's choice.

create table payu_order (
    id                 bigint generated by default as identity primary key,
    txnid              varchar(25)  not null unique,
    loan_id            bigint       not null,
    customer_id        bigint       not null,
    amount_paise       bigint       not null check (amount_paise > 0),
    additional_charges varchar(200),
    status             varchar(16)  not null
        check (status in ('INITIATED', 'PENDING', 'SUCCESS', 'FAILED', 'EXPIRED')),
    mihpayid           varchar(40),
    mode               varchar(16),
    bankcode           varchar(24),
    bank_ref_num       varchar(120),
    fee_paise          bigint,
    paid_on            date,
    error_code         varchar(24),
    payment_id         bigint,
    overpayment        boolean      not null default false,
    review_reason      varchar(40),
    last_checked_at    timestamptz,
    next_check_at      timestamptz,
    check_count        int          not null default 0,
    created_at         timestamptz  not null default now(),
    updated_at         timestamptz  not null default now()
);

create index idx_payu_order_loan on payu_order (loan_id, created_at desc);
create index idx_payu_order_due on payu_order (next_check_at) where status in ('INITIATED', 'PENDING');

do $$
declare c text;
begin
    for c in select conname from pg_constraint
             where conrelid = 'payment'::regclass and contype = 'c'
               and pg_get_constraintdef(oid) ilike '%method%'
    loop
        execute format('alter table payment drop constraint %I', c);
    end loop;
end $$;

alter table payment add constraint payment_method_check
    check (method in ('UPI', 'BANK_TRANSFER', 'NACH', 'PAYU'));

insert into feature_flag (flag_key, enabled, description, created_at)
values ('payu-repayment', false,
        'PayU Hosted Checkout for loan repayments. OFF: the repay page offers manual payment only.',
        now())
on conflict (flag_key) do nothing;
