-- V101 — admin "eSign documents": an admin uploads any PDF (vendor / DSA / employee agreement), names
-- one or more signers (external, or themselves) and each signs by Aadhaar eSign through the same
-- Signzy Contract API the borrower sanction letter uses. One contract per document, one row per signer.
--
-- Deliberately NOT the application_verification ESIGN machinery: that is keyed to a loan application
-- and a single borrower. No foreign keys, per this schema's convention.
--
-- Every contract is real, billable and legally binding with no sandbox, so the feature ships OFF
-- (read with defaultWhenMissing=false). Enable: update feature_flag set enabled = true
-- where flag_key = 'esign-documents';
create table esign_document (
    id                    bigint generated by default as identity primary key,
    title                 varchar(200)  not null,
    file_name             varchar(255)  not null,
    s3_object_key         varchar(512)  not null,
    page_count            integer       not null,
    contract_id           varchar(100),
    status                varchar(20)   not null
        check (status in ('SENT', 'COMPLETED', 'FAILED', 'EXPIRED')),
    error_message         varchar(1000),
    signed_s3_object_key  varchar(512),
    audit_certificate_url varchar(1000),
    created_by            bigint        not null,
    created_at            timestamptz   not null default now(),
    completed_at          timestamptz
);

create index idx_esign_document_contract on esign_document (contract_id);
create index idx_esign_document_created on esign_document (created_at desc, id desc);

create table esign_document_signer (
    id             bigint generated by default as identity primary key,
    document_id    bigint        not null,
    signer_order   integer       not null,
    name           varchar(200)  not null,
    email          varchar(255),
    is_self        boolean       not null default false,
    pages          varchar(100)  not null,
    position       varchar(20)   not null
        check (position in ('TopLeft', 'TopCenter', 'TopRight', 'MiddleLeft', 'MiddleCenter',
                            'MiddleRight', 'BottomLeft', 'BottomCenter', 'BottomRight')),
    signer_id      varchar(100),
    sign_url       varchar(1000),
    status         varchar(20)   not null default 'PENDING'
        check (status in ('PENDING', 'SIGNED', 'FAILED')),
    error_message  varchar(1000),
    signed_at      timestamptz,
    email_status   varchar(20)   not null default 'NOT_SENT'
        check (email_status in ('NOT_SENT', 'SENT', 'FAILED', 'SKIPPED')),
    email_sent_at  timestamptz
);

create index idx_esign_signer_document on esign_document_signer (document_id, signer_order);

insert into feature_flag (flag_key, enabled, description, created_at)
values ('esign-documents', false,
        'Admin eSign documents: upload a PDF and have signers Aadhaar-eSign it (billable, legally binding). '
            || 'OFF: the endpoints refuse and the nav entry is hidden.',
        now())
on conflict (flag_key) do nothing;
