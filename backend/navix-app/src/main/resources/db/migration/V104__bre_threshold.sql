-- Admin-editable numbers behind the BRE rules tab (Staff -> BRE rules). A missing row means the code
-- default (the constants that used to be hard-coded in ApplicationFlowService / BreRuleCatalog), so this
-- migration changes no behaviour. The on/off switches live in feature_flag (bre-* keys), upserted by the
-- app; no seed is needed. Audit columns match BaseAuditEntity (same shape as feature_flag).
create table bre_threshold (
    id            bigint generated by default as identity primary key,
    threshold_key varchar(64)  not null unique,
    value         bigint       not null,
    created_at    timestamp(6) with time zone not null default now(),
    created_by    varchar(255),
    updated_at    timestamp(6) with time zone,
    updated_by    varchar(255)
);
