-- V82 — Mandate: one NACH eMandate registration ATTEMPT via Digio.
--
-- The borrower authorises a standing debit on their salary account at the end of the offer journey
-- (after the disbursal account is confirmed). A mandate is registered with a bank, authorised on the
-- bank's own page, and may fail, be abandoned or expire — and each retry is a NEW Digio mandate with
-- its own id. So the row is per ATTEMPT, not per customer: attempt_no counts up per customer, and
-- customer_ref_number (<customer_id>-<attempt_no>, our reconciliation key and the handle we recover an
-- unknown-outcome register by) is unique. Nothing is ever overwritten between attempts; "the mandate a
-- customer has" is the newest row carrying a umrn.
--
-- UMRN present means ACTIVE, whatever the provider's state strings say — digio_state / digio_bank_state
-- are kept verbatim only so support can read what Digio said. The full account number is NEVER stored;
-- only account_last4. Money is BIGINT paise like everywhere else.
--
-- No FK constraints, indexes only — the repo's documented, deliberate debt.
create table mandate (
    id                    bigint generated by default as identity primary key,
    customer_id           bigint       not null,
    loan_application_id   bigint,
    attempt_no            integer      not null,
    digio_mandate_id      varchar(64)  not null,   -- ENA...
    umrn                  varchar(64),             -- null until the bank has registered the mandate
    customer_ref_number   varchar(20)  not null,
    status                varchar(24)  not null,   -- PENDING_AUTHORIZATION | ACTIVE | AUTHORIZATION_FAILED | EXPIRED | BANK_UNSUPPORTED
    digio_state           varchar(40),
    digio_bank_state      varchar(40),
    auth_mode             varchar(24),
    auth_sub_mode         varchar(24),
    maximum_amount_paise  bigint       not null,
    first_collection_date date,
    final_collection_date date,
    bank_name             varchar(100),
    account_last4         varchar(4),
    ifsc                  varchar(11),
    reject_code           varchar(64),
    reject_reason         varchar(500),
    authenticated_at      timestamptz,
    registered_at         timestamptz,
    created_at            timestamptz  not null default now(),
    created_by            varchar(200),
    updated_at            timestamptz,
    updated_by            varchar(200),
    constraint uq_mandate_digio_id unique (digio_mandate_id),
    constraint uq_mandate_crn unique (customer_ref_number)
);
create unique index uq_mandate_umrn on mandate (umrn) where umrn is not null;
create index ix_mandate_customer on mandate (customer_id);
create index ix_mandate_application on mandate (loan_application_id);
