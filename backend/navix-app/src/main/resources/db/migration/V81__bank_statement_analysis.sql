-- V81 — Bank Statement Analysis: history of on-demand Signzy BSA runs.
--
-- Credit needs the numbers behind a borrower's uploaded statements — identified salary, balances,
-- bounces, and Signzy's own fraud/authenticity verdict per PDF. It is billed per statement analysed
-- and takes minutes, so it is NEVER run by the lifecycle: a Credit Executive, Credit Head or ADMIN
-- triggers it per customer from the Banking tab, and the result is kept here so every later reader
-- (Banking tab, BRE rule 9, Third-party tab) sees it without paying again.
--
-- Keyed by customer like skip_trace (V77) — a person has one set of bank accounts, so the same
-- analysis shows on all of their files; application_id only records where the run was launched from.
--
-- Signzy's flow is ASYNCHRONOUS and spans three calls, which is why this row outlives the request
-- that created it: analyze-statement returns a report_id in status IN PROGRESS, retrieve-work-order
-- reports progress, and download-report hands back the JSON/Excel URLs once ANALYSED. We poll on
-- read (last_polled_at throttles that) rather than exposing a public callback — our row is the
-- source of truth, as it is for DigiLocker and eSign.
create table bank_statement_analysis (
    id                  bigint generated by default as identity primary key,
    customer_id         bigint       not null,
    application_id      bigint,
    status              varchar(20)  not null,   -- PENDING | ANALYSED | FAILED
    report_id           varchar(64),
    report_status       varchar(40),             -- Signzy's own: IN PROGRESS | ANALYSED | ANALYSIS ON HOLD
    report_status_desc  varchar(200),
    bank_score          varchar(16),
    message             varchar(500),
    request_json        jsonb        not null,   -- what we sent, file URLs redacted to their object keys
    response_json       jsonb,                   -- the latest Signzy envelope, verbatim
    report_json_url     text,
    report_excel_url    text,
    duration_ms         bigint,
    last_polled_at      timestamptz,
    run_by_staff_id     bigint       not null,
    run_by_name         varchar(200),
    run_by_role         varchar(40),
    created_at          timestamptz  not null default now(),
    created_by          varchar(200),
    updated_at          timestamptz,
    updated_by          varchar(200)
);

create index idx_bsa_customer on bank_statement_analysis (customer_id, created_at desc);
